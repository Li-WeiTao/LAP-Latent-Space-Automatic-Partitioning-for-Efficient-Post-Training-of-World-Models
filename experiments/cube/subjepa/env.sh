#!/usr/bin/env bash
# Shared OGBench Cube Sub-JEPA paths (source from task-local scripts).
#
# CHECKPOINT defaults to the Sub-JEPA Cube checkpoint found on this server at
# /data/sicong/weitao/.stable_worldmodel/cube/subjepa_object.ckpt. Override it
# explicitly if that checkpoint moves or a different one should be used.
# Merely sourcing this file must never fail; require_checkpoint (below) is
# called by scripts right before the checkpoint is actually used.
set -u

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"

export PYTHON="${PYTHON:-$REPO_ROOT/.venv/bin/python}"
export DATASET="${DATASET:-/home/sicong/weitao/datasets/lewm/cube_single_expert.h5}"
export CHECKPOINT="${CHECKPOINT:-/data/sicong/weitao/.stable_worldmodel/cube/subjepa_object.ckpt}"
export TASK_SPEC="${TASK_SPEC:-configs/experiments/tasks/cube.json}"
export CACHE_DIR="${CACHE_DIR:-/data/sicong/weitao/.stableworldmodel/subjepa/cube}"

export WORK_ROOT="${WORK_ROOT:-experiments/cube/subjepa}"
export SMOKE_ROOT="${SMOKE_ROOT:-experiments/cube/subjepa/smoke}"
export FORMAL="${FORMAL:-experiments/cube/subjepa/formal}"
export MATRIX="${MATRIX:-experiments/cube/subjepa/matrix}"

# Canonical paired eval starts. Cube has no prior Le-WM matrix eval on this
# server (Le-WM Cube checkpoint not found -- see experiments/cube/README.md),
# so there is nothing to reuse yet. These must be generated by Cube's own
# official/baseline evaluation the first time short/long eval runs (matrix
# setup_matrix.sh below fails loudly instead of resampling or borrowing
# another task's starts). Override once Cube official eval starts exist.
export CANON_SHORT="${CANON_SHORT:-experiments/cube/subjepa/matrix/eval/official}"
export CANON_LONG="${CANON_LONG:-experiments/cube/subjepa/matrix_long/eval/official}"

# require_checkpoint: call this from any script right before the checkpoint
# is actually used (training / eval / prepare). Never call it merely to
# source this file.
require_checkpoint() {
  if [[ -z "${CHECKPOINT:-}" ]]; then
    echo "ERROR: CHECKPOINT is not set." >&2
    echo "  Set it explicitly, e.g.:" >&2
    echo "    export CHECKPOINT=/path/to/subjepa_cube_object.ckpt" >&2
    echo "  This script will not guess, download, or default a checkpoint path." >&2
    exit 1
  fi
  if [[ ! -f "$CHECKPOINT" ]]; then
    echo "ERROR: CHECKPOINT does not exist: $CHECKPOINT" >&2
    exit 1
  fi
}
